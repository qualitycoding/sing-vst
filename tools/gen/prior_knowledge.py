"""Generates research/PRIOR_KNOWLEDGE.md (R0) from the knowledge store and this run's lessons.
Usage: python tools/gen/prior_knowledge.py <lessons-store> <knowledge-store> <run-lessons-dir> <out.md>
Every count in the output is computed here (lessons L-20261009T123012Z, L-20261004T102009Z)."""
from __future__ import annotations
import json, pathlib, re, sys, subprocess
from collections import Counter

TASK_TAGS = ["domain:audio", "domain:singing-voice-synthesis", "tech:cpp", "tech:juce", "tech:vst3", "tech:cmake", "tech:msvc",
             "tech:github-actions", "tech:github", "tech:git", "tech:bash", "tech:python", "tech:pytest", "tech:numpy", "tech:scipy",
             "tech:rvc", "tech:diffsinger", "tech:onnxruntime", "tech:onnx", "tech:pytorch", "tech:google-colab", "tech:kaggle",
             "tech:catch2", "tech:pluginval"]
SEV = {"Critical": 0, "High": 1, "Medium": 2, "Low": 3}

# Checklist: PK id -> (rule, where it is applied in this plan). "where" is filled with plan IDs.
CHECKLIST = json.loads(pathlib.Path(__file__).with_name("pk_checklist.json").read_text())
# lesson-id prefix (timestamp part) -> PK ids, or "N/A: reason"
MAP = json.loads(pathlib.Path(__file__).with_name("pk_map.json").read_text())


def fm(text):
    parts = text.split("---", 2)
    head = parts[1] if text.startswith("---") and len(parts) == 3 else ""
    return dict(re.findall(r"^(\w+):[ \t]*(.*)$", head, re.M)), (parts[2] if len(parts) == 3 else "")


def section(body, name):
    m = re.search(r"^## " + re.escape(name) + r"\s*\n(.*?)(?=^## |\Z)", body, re.M | re.S)
    return (m.group(1).strip() if m else "").replace("\n", " ")


def load(root: pathlib.Path, store: bool):
    rows = []
    for p in sorted(root.rglob("L-*.md")):
        f, body = fm(p.read_text(encoding="utf-8"))
        tags = set(re.findall(r"[\w-]+:[\w.-]+", f.get("tags", "")))
        if f.get("status", "active").strip() != "active":
            continue
        match = sorted(tags & set(TASK_TAGS)) + (["applies:all"] if "applies:all" in tags else [])
        if not match:
            continue
        rows.append(dict(id=p.stem, sev=f.get("severity", "Low").strip(), at=f.get("recorded_at", "").strip(),
                         title=f.get("title", "").strip().strip("'\""), match=match, rule=section(body, "Prevention rule"), store=store))
    return rows


def main():
    lessons_store, knowledge_store, run_dir, out = map(pathlib.Path, sys.argv[1:5])
    rows = load(lessons_store / "lessons", True) + load(run_dir, False)
    rows.sort(key=lambda r: (SEV.get(r["sev"], 3), -int(re.sub(r"\D", "", r["at"])[:14] or 0)))
    missing = [r["id"] for r in rows if r["id"][2:18] not in MAP]
    if missing:
        sys.exit("unmapped lessons: " + ", ".join(missing))
    unknown_pk = {pk for v in MAP.values() if not v.startswith("N/A") for pk in v.split(",") if pk.strip() not in CHECKLIST}
    if unknown_pk:
        sys.exit("unknown PK ids in map: " + ", ".join(sorted(unknown_pk)))
    commit = lambda d: subprocess.run(["git", "-C", str(d), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    sev = Counter(r["sev"] for r in rows)
    applied = [r for r in rows if not MAP[r["id"][2:18]].startswith("N/A")]
    L = ["# Prior knowledge (R0)", "",
         f"Store read: `qualitycoding/Lessons` @ `{commit(lessons_store)}`, `qualitycoding/knowledge` @ `{commit(knowledge_store)}`, "
         f"plus this run's own lessons in `lessons/`. Matching rule: Appendix C (any `domain:`/`tech:` tag in the task's set, or `applies:all`; "
         "active entries only). Task tags: " + ", ".join(f"`{t}`" for t in TASK_TAGS) + ".", "",
         f"Lessons matched: **{len(rows)}** (store {sum(r['store'] for r in rows)}, this run {sum(not r['store'] for r in rows)}); "
         f"by severity: " + ", ".join(f"{k} {sev[k]}" for k in SEV if sev[k]) + f". Applied: {len(applied)}; not applicable: {len(rows) - len(applied)}.",
         "Generated by `python tools/gen/prior_knowledge.py` (counts computed, never typed).", "",
         "## Prevention-rule checklist", "",
         "The cold read (3.6) and every pre-mortem round (Phase 4) work from this list. `Applied via` names the decision, test, step or risk "
         "that implements each rule.", "", "| PK | Rule | Applied via | Applies to | Source lessons |", "|---|---|---|---|---|"]
    src = {pk: [] for pk in CHECKLIST}
    for r in rows:
        v = MAP[r["id"][2:18]]
        if not v.startswith("N/A"):
            for pk in v.split(","):
                src[pk.strip()].append(r["id"][:17])
    for pk, (rule, where, who) in CHECKLIST.items():
        L.append(f"| {pk} | {rule} | {where} | {who} | {', '.join(src[pk]) or '—'} |")
    L += ["", "## Per-lesson application", "", "Ordered by severity, then most recent first.", "",
          "| Lesson | Sev | Matched on | Title | Applied as |", "|---|---|---|---|---|"]
    for r in rows:
        v = MAP[r["id"][2:18]]
        L.append(f"| `{r['id']}` | {r['sev']} | {', '.join(r['match'])} | {r['title'][:140].replace('|', '/')} | {v} |")
    L += ["", "## Knowledge items used", "", "Items from `qualitycoding/knowledge` whose tags match; each is used as one source only when its "
          "`applies_to_version` matches the pinned version or is version-independent (R0.4). Seeded claims are listed in `research/claims.json` "
          "under `seeded_from`.", ""]
    L += [f"- `{k}`: {why}" for k, why in json.loads(pathlib.Path(__file__).with_name("pk_knowledge.json").read_text()).items()]
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{len(rows)} lessons, {len(applied)} applied, {len(CHECKLIST)} checklist rules -> {out}")


if __name__ == "__main__":
    main()
