"""Writes plan/PROTOCOL_EXCERPTS.md: the planning-protocol sections the implementer needs, copied verbatim from the pinned
protocol file (cold read H8/S8). Usage: python3.12 tools/gen/protocol_excerpts.py <planning-protocol.md> <commit> [<version> <decision>]
(defaults v3.6, D-041; the run started at v3.3, 9636a79, D-034)."""
import pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
src, commit = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"), sys.argv[2]
version, decision = (sys.argv[3], sys.argv[4]) if len(sys.argv) > 4 else ("v3.6", "D-041")

def between(start, end):
    i = src.index(start); j = src.index(end, i + len(start)) if end else len(src)
    return src[i:j].rstrip()

parts = [
    ("Global Rules 1–14", between("## Global Rules", "\n## Phase 0").rstrip("-\n ")),
    ("3.1 — Step template", between("### 3.1 Step Template", "### 3.2 Decision Rules")),
    ("0.2 — Model tier hierarchy", between("### 0.2 Model Tier Hierarchy", "### 0.3 Intake")),
    ("Phase 5 — GitHub push and termination (planning agent)", between("## Phase 5:", "## Appendix A:")),
    ("1.2.3 — Zero-Context Resumption Protocol", between("#### 1.2.3 Zero-Context Resumption Protocol", "### 1.3 Iterative Research Loop")),
    ("2E.3–2E.4 — Immutability and Test Challenge", between("3. **Immutability Rule:**", "---\n\n## Phase 3")),
    ("3.2 — Default rule", between("* `[All]` **The default rule**", "### 3.3 Human Gates")),
    ("3.3 — Human gates", between("### 3.3 Human Gates", "### 3.4")),
    ("3.7–3.8 — Opening and closing steps; code review steps", between("### 3.7 Opening and Closing Steps", "---\n\n## Phase 4")),
    ("1.3.6 — Command & pin verification", between("#### 1.3.6 Command & Pin Verification", "### 1.4")),
    ("1.5 — Ephemeral-environment protections", between("### 1.5 Ephemeral-Environment Protections", "---\n\n## Phase 2")),
    ("4.7 — Assumption & premise audit", between("### 4.7 Assumption & Premise Audit", "---\n\n## Phase 5")),
    ("Appendices A–C — Lesson and knowledge templates, knowledge store", between("## Appendix A: Lesson Template", None)),
]
out = [f"# Protocol excerpts", "", f"Verbatim from `qualitycoding/skills` `protocols/planning-protocol.md` at `{commit}` ({version}, {decision}).",
       "Generated by `python3.12 tools/gen/protocol_excerpts.py`; do not edit by hand.", ""]
for title, body in parts:
    out += [f"## {title}", "", body, ""]
(ROOT / "plan" / "PROTOCOL_EXCERPTS.md").write_text("\n".join(out), encoding="utf-8")
print("sections", len(parts))
