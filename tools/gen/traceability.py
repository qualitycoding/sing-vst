"""Generates plan/TRACEABILITY.md (2E.1): every test -> requirement(s) and step; every requirement -> tests; fails if any
test is unmapped or any requirement has no test (or gate). Usage: python3.12 tools/gen/traceability.py"""
import pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
tests = {}  # id -> (file, title)
for f in sorted((ROOT / "tests" / "cpp").glob("test_*.cpp")):
    for m in re.finditer(r'TEST_CASE \("(T-\d{3}) ([^"]*)"', f.read_text(encoding="utf-8")):
        tests[m.group(1)] = (f"tests/cpp/{f.name}", m.group(2))
for f in sorted((ROOT / "tests" / "python").glob("test_*.py")):
    for m in re.finditer(r'"""(T-P?\d{2,3}) \(([^)]*)\)', f.read_text(encoding="utf-8")):
        tests.setdefault(m.group(1), (f"tests/python/{f.name}", m.group(2)))
ci = (ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
if "(T-059)" in ci:
    tests["T-059"] = (".github/workflows/ci.yml", "pluginval 1.0.4 strictness 5 on both OSes (C-015, D-023)")

def rng(a, b, p="T-"):
    return {f"{p}{i:03d}" if p == "T-" else f"{p}{i:02d}" for i in range(a, b + 1)}
STEP = {}
for f, s in {"test_lyrics": "S-002", "test_g2p": "S-002", "test_align": "S-002", "test_synthesis": "S-003", "test_voice": "S-004",
             "test_playback": "S-005", "test_midifile": "S-006", "test_runtime": "S-007", "test_engine": "S-008",
             "test_render": "S-009", "test_take_cache": "S-009", "test_limits": "S-009", "test_resample_take": "S-009", "test_plugin": "S-011", "test_prepare": "S-012", "test_pipeline": "S-012",
             "test_provenance": "S-012", "test_metrics": "S-012", "test_pack": "S-012", "test_security": "S-012",
             "test_cli": "S-012", "test_export_rvc": "S-013", "test_rvc_files": "S-014", "test_evaluate": "S-015",
             "test_notebooks": "S-016", "test_cli_binary": "S-010", "test_repo": "S-000"}.items():
    for t, (file, _) in tests.items():
        if pathlib.Path(file).stem == f:
            STEP[t] = s
STEP.update({"T-059": "S-001, S-011", "T-P13": "S-012 (binary part needs the S-010 binary)", "T-P20": "S-017 (owner, G-004)", "T-P23": "S-018",
             "T-P26": "S-015", "T-069": "S-006"})
REQ = {
    "SC-1 builds on Windows x64 and Linux x64": {"T-059"} | rng(39, 41),
    "SC-2 typed/imported lyrics sung on the notes": rng(1, 31) | rng(42, 52) | rng(58, 58) | rng(63, 66) | {"T-P18", "T-P13"},
    "SC-3 host sync, tempo, state (incl. exact take recall, R-017)": rng(32, 38) | rng(53, 57) | rng(67, 68) | {"T-071"},
    "SC-4 speaker similarity (unmeasured default)": {"T-P20", "T-P12"},
    "SC-5 F0 accuracy": {"T-P09", "T-P10", "T-P20"},
    "SC-6 intelligibility (WER)": {"T-P11", "T-P20", "T-P26"},
    "SC-7 render speed (RTF)": {"T-P20"},
    "SC-8 pluginval strictness 5": {"T-059"},
    "SC-9 training on a free hosted GPU, resumable": {"T-P01", "T-P02", "T-P03", "T-P04", "T-P05", "T-P06", "T-P07", "T-P16",
                                                      "T-P17", "T-P19", "T-P24", "T-P25"},
    "SC-10 owner's listening sign-off": set(),  # gate G-001
    "PR-1 provenance and integrity (Rule 9, 2B.2)": {"T-P08", "T-P13", "T-P14", "T-060", "T-P22", "T-P27"},
    "PR-2 security (secrets, untrusted input, dependencies)": {"T-P15", "T-062", "T-P21", "T-005", "T-028", "T-066", "T-069", "T-070"},
    "PR-3 CI keeps running every frozen suite (D-018)": {"T-061"},
    "PR-4 documentation states only tested behaviour (D-030)": {"T-P23"},
}
GATES = {"SC-10 owner's listening sign-off": "G-001", "SC-4 speaker similarity (unmeasured default)": "G-001",
         "SC-7 render speed (RTF)": "G-001", "SC-5 F0 accuracy": "G-001", "SC-6 intelligibility (WER)": "G-001",
         "SC-9 training on a free hosted GPU, resumable": "G-004"}
mapped = set().union(*REQ.values())
unmapped = sorted(set(tests) - mapped)
unknown = sorted(mapped - set(tests))
empty = [r for r, ts in REQ.items() if not ts and r not in GATES]
nostep = sorted(set(tests) - set(STEP))
if unmapped or unknown or empty or nostep:
    sys.exit(f"unmapped tests {unmapped}; unknown {unknown}; requirements without tests {empty}; tests without step {nostep}")
L = ["# Traceability (2E.1)", "", "Generated by `python3.12 tools/gen/traceability.py` (fails if any test or requirement is unmapped).",
     "SC-1…SC-10 are the success criteria of plan/ASSUMPTIONS.md A-012; PR-1…PR-4 are process requirements from the protocol.",
     "Sub-tests named `test_P##b_…` are parts of their parent T-P## (D-037 E-4) and have no row of their own.",
     "T-059 is CI-only: the pluginval step of `.github/workflows/ci.yml` (D-023, D-036), which is its File entry. A Gate of",
     "`—` means the requirement is decided by its tests alone.", "",
     "## Requirements → tests", "", "| Requirement | Tests | Gate |", "|---|---|---|"]
for r, ts in REQ.items():
    L.append(f"| {r} | {', '.join(sorted(ts)) or '—'} | {GATES.get(r, '—')} |")
L += ["", "## Tests → requirement, step", "", "| Test | File | Cites | Requirements | Step |", "|---|---|---|---|---|"]
key = lambda t: (t.startswith("T-P"), t)
for t in sorted(tests, key=key):
    reqs = [r.split(" ")[0] for r, ts in REQ.items() if t in ts]
    f, title = tests[t]
    cites = ", ".join(sorted(set(re.findall(r"\b(?:[CD]-\d{3}|PK-\d{2}|A-\d{3})\b", title)))) or "—"
    L.append(f"| {t} | {f} | {cites} | {', '.join(reqs)} | {STEP[t]} |")
L += ["", f"Totals: {len(tests)} tests, {len(REQ)} requirements."]
(ROOT / "plan" / "TRACEABILITY.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print(len(tests), "tests mapped")
